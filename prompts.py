def profile_to_text(p: dict) -> str:
    lines = []
    for k, label in LABELS.items():
        v = p.get(k)
        if v is None or str(v).strip() == "":
            continue
        if isinstance(v, list):
            v = "、".join(map(str, v))
        lines.append(f"- {label}：{str(v)[:300]}")
    calc = p.get("_calc")
    if isinstance(calc, dict) and calc.get("bmr"):
        lines.append(f"- 本地计算（Mifflin-St Jeor）：BMR≈{calc.get('bmr')} kcal，TDEE≈{calc.get('tdee')} kcal")
    return "\n".join(lines)
